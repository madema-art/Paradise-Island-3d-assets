"""Generate assets/monkey/README.md from MANIFEST.json, monkey_clips.json and the validation reports."""
import json
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
A = os.path.join(ROOT, "assets", "monkey")
clips = json.load(open(os.path.join(A, "monkey_clips.json")))
man = json.load(open(os.path.join(A, "MANIFEST.json")))["files"]
st = json.load(open(os.path.join(A, "validation", "Monkey_structure.json")))
st1 = json.load(open(os.path.join(A, "validation", "Monkey_lod1_structure.json")))
kh = json.load(open(os.path.join(A, "validation", "Monkey_khronos.json")))


def mb(n):
    return f"{n / 1048576:.1f} MB"


ORDER = ["locomotion", "climbing", "behavior", "behaviour", "social", "coconut", "pose"]
groups = {}
for n, m in clips.items():
    groups.setdefault(m.get("group", "other"), []).append(n)

L = []
L.append("# Monkey asset package\n")
L.append("Long-tailed-macaque-like monkey for the Paradise Island Three.js game: one organic skinned mesh, 2048² painted PBR "
         "texture set, 102-joint rig, 41 baked animation clips and a coconut prop. Generated by `tools/monkey/` "
         "(`build_all.sh`); do not edit the GLBs by hand, rebuild them. See `docs/MONKEY_INTEGRATION.md` for the integration guide.\n")
L.append("## Files\n")
L.append("| File | Size | Purpose |\n|---|---|---|")
purpose = {
    "Monkey.glb": "**Runtime asset**: mesh, rig, 2048² textures, all clips (NLA tracks, one animation each).",
    "Monkey_lite.glb": "Same mesh, rig and clips; 1024² albedo/normal and 512² ORM textures (mobile/low tier).",
    "Monkey_lod1.glb": f"Distant LOD ({st1['triangles']:,} tris), no clips, no eyelids. Skin it with the main skeleton's clips.",
    "coconut.glb": "Coconut prop (husk, ridged, 512² textures). Attach to the `coconut_attach` bone when `uses_coconut`.",
    "Monkey.blend": "**Editable source** (Blender 5.2.2): rig with IK controls, weights, materials, baked actions.",
    "Coconut.blend": "Coconut source.",
    "monkey_clips.json": "Per-clip metadata: duration, loop, speed, group, description, QA metrics, pairing.",
    "monkey_bones.json": "Skeleton hierarchy.",
    "MANIFEST.json": "File sizes and hashes.",
}
for f, p in purpose.items():
    if f in man:
        L.append(f"| `{f}` | {mb(man[f]['bytes'])} | {p} |")
L.append("| `textures/` | | Runtime JPEG/PNG textures; `textures/source/` holds lossless originals. |")
L.append("| `validation/` | | Structural and Khronos glTF validator reports for each GLB. |")
L.append("| `previews/` | | Character reference sheet, pose sheets, texture atlas overview, UV layout, turntable, clip GIFs. |\n")
L.append("## Specification\n")
L.append(f"- Body mesh: {st['triangles']:,} triangles in LOD0 (incl. eyes/lids), {st['vertices']:,} glTF vertices; {st['skins'][0]} joints; 4 influences per vertex.")
L.append("- Materials: MonkeyFur (albedo, tangent-space normal, ORM; sheen), MonkeyEye, MonkeyLid, MonkeyLidEdge. One 2048² UV atlas for the body.")
L.append("- Orientation: faces +Z in glTF (Y-up), units metres, ~0.46 m head-body, ~0.95 m with tail.")
L.append(f"- Khronos glTF validator: **{kh['errors']} errors**, {kh['warnings']} warnings (runtime-generated tangents; skinned mesh nodes not at root: benign).\n")
L.append("## Animation clips\n")
L.append("`reach` is the worst IK miss (mm) of any hand/foot target over the clip; `slide` is the deliberate end-effector clamp shift. "
         "Speed is the ground speed the clip assumes (set `timeScale = travelSpeed / speed`).\n")
seen = set()
for g in ORDER + sorted(set(groups) - set(ORDER)):
    if g not in groups or g in seen:
        continue
    seen.add(g)
    L.append(f"### {g.capitalize()}\n")
    L.append("| Clip | s | Loop | Speed m/s | Reach mm | Slide mm | Notes |\n|---|---|---|---|---|---|---|")
    for n in groups[g]:
        m = clips[n]
        reach = max(m["reach_error_mm"].values()) if m.get("reach_error_mm") else 0
        sp = f"{m['speed_mps']:.2f}" if m.get("speed_mps") else ""
        desc = (m.get("description") or "").replace("|", "/")
        desc = desc if len(desc) < 230 else desc[:227] + "…"
        L.append(f"| `{n}` | {m['seconds']:.2f} | {'yes' if m['loop'] else 'no'} | {sp} | {reach:.1f} | {m.get('clamp_shift_mm', 0):.1f} | {desc} |")
    L.append("")
open(os.path.join(A, "README.md"), "w").write("\n".join(L))
print("wrote", os.path.join(A, "README.md"))
